//! Linker setup, and the web UI embedded into the firmware: every file of
//! `ui/packages/frontend/dist` becomes a `static` byte slice (`.gz` files are served
//! with `Content-Encoding: gzip` under their name without `.gz`).

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::{env, fs};

fn main() {
    let dir = env::var("CARGO_MANIFEST_DIR").unwrap();
    println!("cargo:rustc-link-search={dir}/ld");
    println!("cargo:rerun-if-changed=ld");
    println!("cargo:rustc-link-arg=-Trom-fixups.x");
    println!("cargo:rustc-link-arg=-Tlinkall.x");

    let dist = env::var("CC_UI_DIST").map_or_else(
        |_| Path::new(&dir).join("../ui/packages/frontend/dist"),
        PathBuf::from,
    );
    println!("cargo:rerun-if-env-changed=CC_UI_DIST");
    println!("cargo:rerun-if-changed={}", dist.display());
    let mut files = Vec::new();
    if dist.is_dir() {
        collect(&dist, &dist, &mut files);
    }
    files.sort();

    let mut out = String::from(
        "// Generated by build.rs from the web UI build.\n\npub static ASSETS: &[(&str, &[u8], &str, bool)] = &[\n",
    );
    if files.is_empty() {
        println!(
            "cargo:warning=web UI not built ({}): serving a placeholder. Run `just ui`.",
            dist.display()
        );
        out.push_str(
            "    (\"index.html\", b\"<!doctype html><title>CleverCoffee</title><p>The web UI was not built into this firmware. Run <code>just ui</code> and rebuild.\", \"text/html\", false),\n",
        );
    }
    for rel in &files {
        let abs = dist.join(rel);
        println!("cargo:rerun-if-changed={}", abs.display());
        let (served, gzip) = match rel.strip_suffix(".gz") {
            Some(s) => (s.to_string(), true),
            None => (rel.clone(), false),
        };
        // Prefer the gzip variant when both exist.
        if !gzip && files.contains(&format!("{rel}.gz")) {
            continue;
        }
        let _ = writeln!(
            out,
            "    ({served:?}, include_bytes!({:?}), {:?}, {gzip}),",
            abs.canonicalize().unwrap().display().to_string(),
            content_type(&served)
        );
    }
    out.push_str("];\n");
    fs::write(Path::new(&env::var("OUT_DIR").unwrap()).join("ui_assets.rs"), out).unwrap();
}

fn collect(root: &Path, dir: &Path, out: &mut Vec<String>) {
    for e in fs::read_dir(dir).unwrap().flatten() {
        let p = e.path();
        if p.is_dir() {
            collect(root, &p, out);
        } else {
            out.push(p.strip_prefix(root).unwrap().to_string_lossy().replace('\\', "/"));
        }
    }
}

fn content_type(path: &str) -> &'static str {
    match path.rsplit('.').next().unwrap_or("") {
        "html" => "text/html",
        "js" | "mjs" => "application/javascript",
        "css" => "text/css",
        "json" | "webmanifest" => "application/json",
        "svg" => "image/svg+xml",
        "png" => "image/png",
        "ico" => "image/x-icon",
        "woff2" => "font/woff2",
        "txt" => "text/plain",
        _ => "application/octet-stream",
    }
}
