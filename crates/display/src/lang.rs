//! Display texts per language (from the C++ `languages.h`).

use cc_core::config::Language;

#[derive(Debug)]
pub struct Texts {
    pub set_temp: &'static str,
    pub current_temp: &'static str,
    pub brew: &'static str,
    pub weight: &'static str,
    pub manual_flush: &'static str,
    pub hot_water: &'static str,
    pub pressure: &'static str,
    pub set_temp_ur: &'static str,
    pub current_temp_ur: &'static str,
    pub brew_ur: &'static str,
    pub manual_flush_ur: &'static str,
    pub hot_water_ur: &'static str,
    pub weight_ur: &'static str,
    pub pressure_ur: &'static str,
    pub offline: &'static str,
    pub connect_wifi: &'static str,
    pub no_wifi: [&'static str; 2],
    pub error_tsensor: [&'static str; 2],
    pub error_tsensor_ur: [&'static str; 5],
    pub scale_failure: &'static str,
    pub backflush_press: &'static str,
    pub backflush_start: &'static str,
    pub backflush_finish: &'static str,
    pub backflush_reminder: [&'static str; 3],
    pub calibrate_start: &'static str,
    pub calibrate_in_progress: &'static str,
    pub calibrate_complete: &'static str,
    pub calibrate_failed: &'static str,
    pub pid_disabled: &'static str,
    pub standby: &'static str,
}

pub fn texts(l: Language) -> &'static Texts {
    match l {
        Language::English => &EN,
        Language::German => &DE,
        Language::Spanish => &ES,
    }
}

