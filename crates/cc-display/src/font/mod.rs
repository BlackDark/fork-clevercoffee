/// The Latin-1 code point a `char` stands for.
///
/// U8g2's ASCII entry points walk a string a *byte* at a time
/// (`u8x8_ascii_next`, `u8g2_font.c:1467`) and the firmware's strings are
/// Latin-1: the degree sign is `static_cast<char>(176)`, one `0xB0` byte.
///
/// A Rust `&str` cannot hold a lone `0xB0` -- it is not valid UTF-8 -- so
/// `"\u{b0}"` is *two* bytes, and a byte walk would look up `0xC2` then `0xB0`
/// and measure 30 px instead of the measured 25 px in `profont10`. Folding the
/// code point back to a single value makes the two agree on every string the
/// firmware draws (ASCII, plus that one byte).
#[must_use]
pub(crate) fn latin1_of(c: char) -> u16 {
    let v = c as u32;
    if v <= 0xff {
        #[allow(
            clippy::cast_possible_truncation,
            reason = "the value is checked to be <= 0xFF above"
        )]
        return v as u16;
    }
    0xffff
}

/// A `char` as the code point to look up in a font.
///
/// Used by the UTF-8 entry points, where a code point above Latin-1 is looked up
/// as itself. None of the ten embedded fonts carry such a glyph, so the result
/// is a missing glyph either way; the distinction is kept so the arithmetic
/// matches U8g2's for a font that did.
#[must_use]
pub(crate) fn code_point_of(c: char) -> u16 {
    let v = c as u32;
    if v <= 0xffff {
        #[allow(
            clippy::cast_possible_truncation,
            reason = "the value is checked to be <= 0xFFFF above"
        )]
        return v as u16;
    }
    0xffff
}

#[cfg(test)]
mod tests {
    use super::*;

    /// One of the ten fonts, named.
    type NamedFont = (&'static str, fn() -> Font);

    /// The ten fonts the templates use, so a parametrised check covers all.
    const ALL: [NamedFont; 10] = [
        ("profont10", profont10),
        ("profont11", profont11),
        ("profont12", profont12),
        ("profont15", profont15),
        ("profont17", profont17),
        ("profont22", profont22),
        ("fub17", fub17),
        ("fub20", fub20),
        ("fub25", fub25),
        ("fub30", fub30),
    ];

    #[test]
    fn every_font_has_a_plausible_header() {
        for (name, make) in ALL {
            let f = make();
            let i = f.info();
            assert!(i.glyph_cnt > 0, "{name}: glyph_cnt is 0");
            assert!(
                i.max_char_width > 0,
                "{name}: max_char_width is not positive"
            );
            assert!(
                i.max_char_height > 0,
                "{name}: max_char_height is not positive"
            );
            // The RLE field widths must be sane or the decoder reads garbage.
            for (field, v) in [
                ("bits_per_0", i.bits_per_0),
                ("bits_per_1", i.bits_per_1),
                ("bits_per_char_width", i.bits_per_char_width),
                ("bits_per_char_height", i.bits_per_char_height),
                ("bits_per_char_x", i.bits_per_char_x),
                ("bits_per_char_y", i.bits_per_char_y),
                ("bits_per_delta_x", i.bits_per_delta_x),
            ] {
                assert!((1..=8).contains(&v), "{name}: {field} = {v}, outside 1..=8");
            }
        }
    }

    #[test]
    fn glyph_walk_stays_inside_the_font() {
        // A mis-parsed header makes the linear glyph-table walk run off the
        // end, so this catches the whole `start_pos_*` mechanism.
        for (name, make) in ALL {
            let f = make();
            for e in 0u16..=255 {
                if let Some(h) = f.glyph_header(e) {
                    assert!(
                        h.data < f.raw().len(),
                        "{name}: glyph {e} points past the end"
                    );
                }
            }
        }
    }

    #[test]
    fn digits_are_monotonic_in_advance() {
        // Not a U8g2 invariant, but a cheap smoke test that the delta-x field
        // is being read: a font where every digit had the same advance would
        // mean `bits_per_delta_x` or the glyph offsets are wrong.
        for (name, make) in ALL {
            let f = make();
            let zero = f.glyph_header(u16::from(b'0')).expect("digit 0");
            let one = f.glyph_header(u16::from(b'1')).expect("digit 1");
            assert!(
                zero.delta_x > 0 && one.delta_x > 0,
                "{name}: digit advance is not positive"
            );
        }
    }

    #[test]
    fn string_width_is_the_sum_of_advances_minus_the_last_side_bearing() {
        // Reproduce U8g2's own arithmetic on a case we can check by hand from
        // the header, rather than trusting a golden number nobody derived.
        let f = profont11();
        let zero = f.glyph_header(u16::from(b'0')).unwrap();
        let text = "000";
        let by_advances = 3 * i32::from(zero.delta_x);
        assert_eq!(
            f.str_width(text),
            by_advances - i32::from(zero.delta_x)
                + i32::from(zero.width)
                + i32::from(zero.x_offset)
        );
    }

    #[test]
    fn width_is_additive_across_a_repeated_glyph() {
        // "N x" is (N-1) advances plus the last glyph's ink, so adding one more
        // character adds exactly one advance. This is the property the
        // fixed-width-field helpers depend on.
        let f = fub20();
        let one = f.str_width("8");
        let two = f.str_width("88");
        let three = f.str_width("888");
        let advance = i32::from(f.glyph_header(u16::from(b'8')).unwrap().delta_x);
        assert_eq!(two - one, advance);
        assert_eq!(three - two, advance);
    }

    #[test]
    fn ref_box_heights_match_the_cpp_probe() {
        // Measured from the real U8g2 (see the `ref_heights` table in this
        // module's docs and `crates/cc-display/tests/parity.rs`): with
        // `setFontRefHeightExtendedText()`, `getFontAscent()` and
        // `getFontDescent()` return these. The C++ templates never read them
        // directly, but they determine where ink lands under `setFontPosTop()`,
        // so a drift here moves every glyph.
        assert_eq!((fub20().ref_height(HeightMode::ExtendedText)), (20, -5));
        assert_eq!((profont17().ref_height(HeightMode::ExtendedText)), (13, -3));
        assert_eq!((profont11().ref_height(HeightMode::ExtendedText)), (8, -2));
        assert_eq!((profont10().ref_height(HeightMode::ExtendedText)), (7, -2));
        assert_eq!((fub30().ref_height(HeightMode::ExtendedText)), (31, -7));
    }

    #[test]
    fn ink_box_matches_the_cpp_measured_ink() {
        // Oracle numbers: draw at y=20, read the framebuffer, report the ink
        // extent. `tools/display_oracle.cpp` reproduces this.
        //
        //   fub20   "100.0" -> y=21..40  (20 rows)
        //   fub20   "Ay"    -> y=21..45  (25 rows, descender of y)
        //   profont17 "Ay"  -> y=23..36  (14 rows)
        let (_, top, _, bottom) = fub20().ink_box("100.0");
        assert_eq!((top + 20, bottom + 20), (21, 40));

        let (_, top, _, bottom) = fub20().ink_box("Ay");
        assert_eq!((top + 20, bottom + 20), (21, 45));

        let (_, top, _, bottom) = profont17().ink_box("Ay");
        assert_eq!((top + 20, bottom + 20), (23, 36));
    }

    #[test]
    fn a_blank_string_has_no_ink_box() {
        assert_eq!(fub20().ink_box("   "), (0, 0, -1, -1));
        assert_eq!(fub20().ink_box(""), (0, 0, -1, -1));
    }

    #[test]
    fn space_has_no_ink_but_still_advances() {
        let f = profont11();
        let sp = f.glyph_header(u16::from(b' ')).expect("space");
        assert_eq!(sp.width, 0, "space should have zero ink width");
        assert!(sp.delta_x > 0, "space should still advance the pen");
        assert_eq!(f.str_width(" "), i32::from(sp.delta_x));
    }

    #[test]
    fn a_missing_glyph_contributes_nothing() {
        // fub fonts have no degree sign in some builds; a missing glyph must
        // not panic and must not add width.
        let f = fub20();
        let w = f.str_width("\u{fffd}");
        assert!(w >= 0);
    }

    #[test]
    fn bit_reader_reads_lsb_first() {
        // U8g2 reads bits LSB-first within a byte, straddling byte boundaries.
        // The bytes are `0b1011_0101`, `0b0000_1110`, `0b0000_0000`.
        //
        //   read 3 -> 0b101 = 5, no straddle
        //   read 5 -> 0b1011_0101 >> 3 = 0b1_0110, & 0b1_1111 = 0b1_0110
        //   read 8 -> straddle (bit_pos 0 + 8 >= 8): the high part contributes
        //             nothing, so this is byte[1] = 0b0000_1110
        let bytes = [0b1011_0101u8, 0b0000_1110u8, 0b0000_0000u8];
        let mut r = BitReader::new(&bytes, 0);
        assert_eq!(r.unsigned(3), 0b101);
        assert_eq!(r.unsigned(5), 0b1_0110);
        assert_eq!(r.unsigned(8), 0b0000_1110);
        assert_eq!(r.offset(), 2);
    }

    #[test]
    fn an_eight_bit_read_always_consumes_a_ninth_byte() {
        // Reproduced deliberately, not as an oversight. U8g2's
        // `u8g2_font_decode_get_unsigned_bits` advances `decode_ptr` and reads
        // the next byte whenever `bit_pos + cnt >= 8` — which is *also* true
        // for `bit_pos == 0, cnt == 8`, where the extra byte contributes
        // nothing because the result is masked to 8 bits. Every U8g2 font
        // therefore has one padding byte after the last field read at a byte
        // boundary, and the embedded arrays are sized for it.
        //
        // This port keeps the behaviour, so its slice bounds match U8g2's and a
        // read that runs off the end is a genuine font defect rather than a
        // silently-different result.
        let bytes = [0b1111_1111u8, 0b1010_1010u8];
        let mut r = BitReader::new(&bytes, 0);
        assert_eq!(r.unsigned(8), 0b1111_1111);
        assert_eq!(
            r.offset(),
            1,
            "the pointer advanced even though nothing was needed"
        );
    }

    #[test]
    fn signed_reads_are_offset_binary() {
        // `u8g2_font_decode_get_signed_bits` subtracts the midpoint
        // `1 << (cnt-1)`. So a `cnt`-bit field reads as
        // `value - 2^(cnt-1)`, i.e. OFFSET BINARY, not two's complement: the
        // all-zero pattern is `-2^(cnt-1)`, and the midpoint pattern
        // (top bit set, rest clear) is zero.
        //
        // Two 4-bit reads need two bytes: the second straddles.
        let bytes = [0b0000_1000u8, 0b0000_0000u8];
        let mut r = BitReader::new(&bytes, 0);
        assert_eq!(r.signed(4), 0, "0b1000 is the midpoint, so 0");
        assert_eq!(r.signed(4), -8, "0b0000 is the minimum, so -8");
    }
}
